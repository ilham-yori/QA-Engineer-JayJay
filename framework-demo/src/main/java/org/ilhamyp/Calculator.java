package org.ilhamyp;

public class Calculator {

    public static int multiply (int a, int b){
        return a * b;
    }

    public static int plus (int a, int b){
        return a + b;
    }

    public static int minus (int a, int b){
        return a - b;
    }

    public static int distribution( int a, int b){
        return a / b;
    }
}
